#!/usr/bin/env python3
"""
Bake a radar basemap for the desktop simulator (sim env).

On a real device the basemap is generated by the browser on the settings web page
(src/services/settings_web.cpp, "Radar basemap" card) and uploaded to the device.
The simulator has no web page, so this script does the same bake in Python —
same tile sources, zoom choice, projection, rotation and color adjustments — and
writes the result straight into the simulator's storage:

  sim_data/littlefs/basemap.jpg      the image (panel size, e.g. 720x720)
  sim_data/nvs.txt  [fs_basemap]     en/ok/lat/lon/mi/fac/sty metadata

The radar shows it when the stored center/facing match and the live range is
<= the baked range (zooming in upscales; zooming out past it needs a re-bake).

Usage (simulator closed — it rewrites nvs.txt while running):
  python tools/sim_bake_basemap.py --style vfr
  python tools/sim_bake_basemap.py --style dark --carto-key YOUR_KEY [--miles 10]
  python tools/sim_bake_basemap.py --off          # hide the map again

Styles: dark / light / voyager (CARTO, free key from carto.com/basemaps/apikey)
        vfr (FAA VFR Sectional via ArcGIS, US only, no key).
Map data: (c) OpenStreetMap contributors, (c) CARTO; FAA VFR charts are public domain.
"""

from __future__ import annotations

import argparse
import io
import math
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

try:
    import numpy as np
    from PIL import Image
except ImportError:
    print("Needs numpy and Pillow:  python -m pip install --user numpy pillow")
    sys.exit(1)

ROOT = Path(__file__).resolve().parent.parent
PANEL = 720            # LCD_WIDTH of the board the simulator emulates (Waveshare 4C)
DESIGN = 390           # ui/ui_scale.h kUiDesignPx; radar_theme.h kGridOuterRadius
OUTER = (PANEL * 174) // DESIGN
CX = CY = PANEL // 2
RANGE_OPTIONS = [2, 3, 6, 8, 10, 20, 30]  # radar_scale.h kRangeMileOptions
STYLE_IDS = {"dark": 0, "light": 1, "vfr": 2, "voyager": 3}  # radar_basemap.h Style
FILL = {"dark": (2, 15, 3), "light": (240, 240, 240), "voyager": (242, 239, 230),
        "vfr": (248, 248, 242)}
USER_AGENT = "FlightScnr-sim-basemap/1.0 (+https://github.com/yashmulgaonkar/FlightScnr)"
EARTH_R_KM = 6371.0088
LABELS = False  # --labels


# --- simulator NVS (sim/src/sim_storage.cpp format: "ns\tkey\tvalue", escaped) ---

def _unescape(v: str) -> str:
    out, i = [], 0
    while i < len(v):
        if v[i] == "\\" and i + 1 < len(v):
            n = v[i + 1]
            out.append("\n" if n == "n" else "\t" if n == "t" else n)
            i += 2
        else:
            out.append(v[i])
            i += 1
    return "".join(out)


def _escape(v: str) -> str:
    return v.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")


def load_nvs(path: Path) -> dict[tuple[str, str], str]:
    data: dict[tuple[str, str], str] = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            parts = line.split("\t", 2)
            if len(parts) == 3:
                data[(parts[0], parts[1])] = _unescape(parts[2])
    return data


def save_nvs(path: Path, data: dict[tuple[str, str], str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"{ns}\t{k}\t{_escape(v)}" for (ns, k), v in sorted(data.items())]
    tmp = path.with_suffix(".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def fmt_double(v: float) -> str:
    return f"{v:.17g}"


# --- projection (same math as the settings page bake script) ---

def merc_x(lon):
    return (lon + 180.0) / 360.0


def merc_y(lat):
    s = np.sin(np.radians(lat))
    return 0.5 - np.log((1 + s) / (1 - s)) / (4 * math.pi)


def pick_zoom(label_km: float, lat: float, style: str) -> int:
    mpp = (label_km * 1000.0) / OUTER
    z = round(math.log2(156543.03392 * math.cos(math.radians(lat)) / mpp))
    return max(8, min(12, z)) if style == "vfr" else max(6, min(15, z))


def tile_url(style: str, z: int, x: int, y: int, key: str | None) -> str:
    if style == "vfr":
        return ("https://tiles.arcgis.com/tiles/ssFJjBXIUyZDrSYZ/arcgis/rest/services/"
                f"VFR_Sectional/MapServer/tile/{z}/{y}/{x}")
    if style == "voyager" and LABELS:
        path = "rastertiles/voyager"  # with town / road names (they rotate with facing)
    else:
        path = {"light": "rastertiles/light_nolabels",
                "voyager": "rastertiles/voyager_nolabels"}.get(style, "rastertiles/dark_nolabels")
    url = f"https://a.basemaps.cartocdn.com/{path}/{z}/{x}/{y}.png"
    if key:
        url += "?key=" + urllib.parse.quote(key)
    return url


def fetch_tile(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            return Image.open(io.BytesIO(resp.read())).convert("RGB")
    except (urllib.error.URLError, OSError) as e:
        return e


def offsets_to_latlon(ex_km, ny_km, lat, lon, facing_deg):
    f = math.radians(facing_deg)
    cf, sf = math.cos(f), math.sin(f)
    e = ex_km * cf + ny_km * sf
    n = -ex_km * sf + ny_km * cf
    d_lat = np.degrees(n / EARTH_R_KM)
    d_lon = np.degrees(e / (EARTH_R_KM * math.cos(math.radians(lat))))
    return lat + d_lat, lon + d_lon


def bake(style, lat, lon, miles, facing, key, contrast_pct, wash_pct) -> Image.Image:
    label_km = miles * 1.609344
    ppm = OUTER / label_km  # panel pixels per km
    z = pick_zoom(label_km, lat, style)
    n = 2 ** z

    # Tile range covering the whole square panel (corners included), +1 margin.
    cover_r = math.ceil(math.hypot(CX, CY)) + 2
    angles = np.radians(np.arange(0, 360, 30))
    c_lat, c_lon = offsets_to_latlon(np.sin(angles) * cover_r / ppm,
                                     np.cos(angles) * cover_r / ppm, lat, lon, facing)
    tx, ty = merc_x(c_lon) * n, merc_y(c_lat) * n
    x0, x1 = int(math.floor(tx.min())) - 1, int(math.ceil(tx.max())) + 1
    y0, y1 = int(math.floor(ty.min())) - 1, int(math.ceil(ty.max())) + 1
    jobs = [(x, y) for x in range(x0, x1 + 1) for y in range(y0, y1 + 1)]
    print(f"  {style} @ {miles} mi, zoom {z}, {len(jobs)} tiles ...")

    fill = FILL[style]
    mosaic = Image.new("RGB", ((x1 - x0 + 1) * 256, (y1 - y0 + 1) * 256), fill)
    got, errors = 0, []
    with ThreadPoolExecutor(max_workers=8) as pool:
        results = pool.map(lambda xy: (xy, fetch_tile(tile_url(style, z, xy[0], xy[1], key))),
                           jobs)
        for (x, y), img in results:
            if isinstance(img, Image.Image) and np.asarray(img, dtype=np.float32).std() < 2.0:
                # Flat "no data" tile (e.g. the FAA chart service over open water):
                # leave the paper-colored background instead of a gray block.
                errors.append("blank tile")
                continue
            if isinstance(img, Image.Image):
                mosaic.paste(img, ((x - x0) * 256, (y - y0) * 256))
                got += 1
            else:
                errors.append(img)
    if got == 0:
        detail = errors[0] if errors else "no tiles"
        hint = (" (check the CARTO key)" if style != "vfr"
                else " (VFR charts cover the US only)")
        raise SystemExit(f"No tiles loaded: {detail}{hint}")
    if errors:
        print(f"  {len(errors)} tiles missing (filled with background)")

    src = np.asarray(mosaic, dtype=np.float32)
    th, tw = src.shape[:2]

    # Panel pixel -> km offsets (screen y up = north before facing rotation).
    py, px = np.mgrid[0:PANEL, 0:PANEL].astype(np.float64)
    p_lat, p_lon = offsets_to_latlon((px - CX) / ppm, (CY - py) / ppm, lat, lon, facing)
    fx = (merc_x(p_lon) * n - x0) * 256
    fy = (merc_y(p_lat) * n - y0) * 256
    xi, yi = np.floor(fx).astype(np.int64), np.floor(fy).astype(np.int64)
    valid = (xi >= 0) & (yi >= 0) & (xi + 1 < tw) & (yi + 1 < th)
    xi, yi = np.clip(xi, 0, tw - 2), np.clip(yi, 0, th - 2)
    wx, wy = (fx - xi)[..., None], (fy - yi)[..., None]
    top = src[yi, xi] * (1 - wx) + src[yi, xi + 1] * wx
    bot = src[yi + 1, xi] * (1 - wx) + src[yi + 1, xi + 1] * wx
    out = top * (1 - wy) + bot * wy

    if style == "vfr" and wash_pct > 0:
        wash = wash_pct / 100.0
        out = out * (1 - wash) + 255.0 * wash
    elif style != "vfr" and contrast_pct != 100:
        out = (out - 128.0) * (contrast_pct / 100.0) + 128.0
    out[~valid] = fill
    return Image.fromarray(np.clip(np.rint(out), 0, 255).astype(np.uint8), "RGB")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--style", choices=sorted(STYLE_IDS), default="vfr")
    ap.add_argument("--miles", type=int, choices=RANGE_OPTIONS,
                    help="bake coverage (default: the simulator's current range)")
    ap.add_argument("--carto-key", default=os.environ.get("CARTO_API_KEY", ""),
                    help="CARTO basemaps key for dark/light/voyager (or env CARTO_API_KEY)")
    ap.add_argument("--data", type=Path, default=ROOT / "sim_data",
                    help="simulator data folder (default: sim_data)")
    ap.add_argument("--lat", type=float, help="radar center latitude (also saved for the sim)")
    ap.add_argument("--lon", type=float, help="radar center longitude")
    ap.add_argument("--off", action="store_true", help="turn the basemap off")
    ap.add_argument("--labels", action="store_true",
                    help="voyager only: keep town and road names on the map")
    args = ap.parse_args()
    global LABELS
    LABELS = args.labels

    nvs_path = args.data / "nvs.txt"
    nvs = load_nvs(nvs_path)
    if args.off:
        nvs[("fs_basemap", "en")] = "0"
        save_nvs(nvs_path, nvs)
        print("Basemap off.")
        return 0

    if args.lat is not None and args.lon is not None:
        # Same keys the simulator's --lat/--lon write, so the bake and the radar agree.
        nvs[("fs_geo", "center_lat")] = fmt_double(args.lat)
        nvs[("fs_geo", "center_lon")] = fmt_double(args.lon)
    try:
        lat = float(nvs[("fs_geo", "center_lat")])
        lon = float(nvs[("fs_geo", "center_lon")])
    except KeyError:
        print("No radar center in the simulator yet. Run it once with --lat/--lon first.")
        return 1
    miles = args.miles or int(nvs.get(("flightscnr", "range_mi"), "8"))
    facing = int(nvs.get(("flightscnr", "facing_deg"), "0") or 0)
    contrast = int(nvs.get(("fs_basemap",
                            "ctr_d" if args.style == "dark" else "ctr_l"), "100") or 100)
    wash = int(nvs.get(("fs_basemap", "wsh_v"), "55") or 55)

    if args.style != "vfr" and not args.carto_key:
        # Same rule as the settings page: without a key CARTO still answers with
        # 200s, but every tile is an "API KEY REQUIRED" placeholder.
        print("CARTO styles (dark/light/voyager) need a free API key from "
              "https://carto.com/basemaps/apikey\n"
              "  pass --carto-key KEY (launcher: -CartoKey KEY) or set CARTO_API_KEY,\n"
              "  or use --style vfr (FAA chart, no key).")
        return 2
    print(f"Baking basemap for {lat:.5f}, {lon:.5f} facing {facing} deg")
    img = bake(args.style, lat, lon, miles, facing, args.carto_key or None, contrast, wash)

    out = args.data / "littlefs" / "basemap.jpg"
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, "JPEG", quality=88, optimize=True)  # baseline, like canvas.toBlob
    size_kb = out.stat().st_size / 1024
    print(f"  wrote {out} ({size_kb:.0f} KB)")

    # Sharper copies for every smaller zoom preset (same as the settings page on
    # the 4C): the radar draws the closest one instead of upscaling the main bake.
    mask = 0
    for i, r in enumerate(RANGE_OPTIONS):
        detail_path = args.data / "littlefs" / f"basemap_{r}.jpg"
        if detail_path.exists():
            detail_path.unlink()
        if r >= miles:
            continue
        bake(args.style, lat, lon, r, facing, args.carto_key or None, contrast,
             wash).save(detail_path, "JPEG", quality=88, optimize=True)
        mask |= 1 << i
    nvs[("fs_basemap", "lvl")] = str(mask)

    nvs.update({
        ("fs_basemap", "en"): "1",
        ("fs_basemap", "ok"): "1",
        ("fs_basemap", "lat"): fmt_double(lat),
        ("fs_basemap", "lon"): fmt_double(lon),
        ("fs_basemap", "mi"): str(miles),
        ("fs_basemap", "fac"): str(facing),
        ("fs_basemap", "sty"): str(STYLE_IDS[args.style]),
    })
    save_nvs(nvs_path, nvs)
    print(f"Basemap on: {args.style}, {miles} mi plus sharper copies for each closer zoom. "
          f"Zooming out past {miles} mi or moving the center needs a re-bake.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
